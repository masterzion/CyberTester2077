const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const YAML = require('yaml');
const root = path.resolve(__dirname, '..');
const settings = YAML.parse(fs.readFileSync(path.join(root, 'automation_tests/automation-settings.yml'), 'utf8'));
const creds = YAML.parse(fs.readFileSync(path.join(root, 'automation_tests/credentials.yml'), 'utf8')) || {};
settings.documentation = { ...settings.documentation, ...creds.documentation };
const source = path.resolve(root, settings.documentation.source_folder);
function walk(dir) { return fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(dir,e.name)) : /\.md$/i.test(e.name) ? [path.join(dir,e.name)] : []); }
const smallest = walk(source).sort((a,b) => fs.statSync(a).size-fs.statSync(b).size)[0];
if (!smallest) throw new Error('No source Markdown files');
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const before = hash(smallest);
const run = path.join(root, 'automation_tests', new Date().toISOString().replace(/[:.]/g,'-')+'-docs-smoke');
fs.mkdirSync(path.join(run,'source'), {recursive:true});
fs.copyFileSync(smallest,path.join(run,'source',path.basename(smallest)));
settings.documentation.source_folder = path.join(run,'source');
settings.documentation.destination_folder = path.join(run,'destination');
const config = path.join(run,'settings.yml');
fs.writeFileSync(config,YAML.stringify(settings));
console.log(JSON.stringify({source:smallest,bytes:fs.statSync(smallest).size,model:settings.llm.model,run}));
const result = spawnSync(process.execPath,[path.join(root,'temporary-categorize-main-docs.cjs'),'--apply'],{cwd:root,env:{...process.env,AUTOMATION_SETTINGS:config,AUTOMATION_CREDENTIALS:path.join(run,'no-credentials.yml')},encoding:'utf8',timeout:240000});
fs.writeFileSync(path.join(run,'run.log'),(result.stdout||'')+'\n'+(result.stderr||''));
console.log(result.stdout||'',result.stderr||'');
const destination = settings.documentation.destination_folder;
const files = fs.existsSync(destination) ? fs.readdirSync(destination) : [];
console.log(JSON.stringify({exitCode:result.status,error:result.error?.message,sourceUnchanged:before===hash(smallest),files,run}));
process.exitCode = result.status === 0 && files.length && before===hash(smallest) ? 0 : 1;
